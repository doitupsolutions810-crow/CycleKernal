"""
Container Sub-Agent
===================
Generates Dockerfiles and compose snippets for sandboxed runtimes.
Does not require a live Docker daemon — emits build specs and optional dry-run checks.
"""

from __future__ import annotations

import logging
import os
import textwrap
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from .base import AgentResult, BaseAgent

logger = logging.getLogger("ck.container")

ARTIFACT_ROOT = Path(os.environ.get("CK_ARTIFACT_ROOT", "/tmp/ck-artifacts"))


class ContainerAgent(BaseAgent):
    name = "container"
    role = "Dockerfile / compose generation for sandboxed workloads"

    async def run(self, task: Dict[str, Any]) -> AgentResult:
        started = datetime.utcnow()
        mood = await self.current_mood()

        name: str = task.get("name") or "ck-sandbox"
        artifact_root: Optional[str] = task.get("artifact_root")
        entry: str = task.get("entry") or "artifact.py"
        base_image: str = task.get("base_image") or "python:3.12-slim"
        ports: List[int] = list(task.get("ports") or [])
        env: Dict[str, str] = dict(task.get("env") or {})
        workdir: str = task.get("workdir") or "/app"

        # Prefer artifact agent output if threaded through
        if not artifact_root and task.get("manifest"):
            artifact_root = task["manifest"].get("root")
            entry = task["manifest"].get("entry") or entry

        survival = any("Survival" in t for t in (mood.get("traits") or []))
        # Hardened defaults under survival mood
        user_line = "USER nobody" if survival else "# USER root (dev)"
        network = task.get("network", "none" if survival else "bridge")

        dockerfile = textwrap.dedent(f'''\
            # Generated by CycleKernel ContainerAgent
            # Mood: {mood.get("mood")}
            FROM {base_image}
            WORKDIR {workdir}
            ENV PYTHONDONTWRITEBYTECODE=1 \\
                PYTHONUNBUFFERED=1
            # Sandbox: copy only the artifact tree
            COPY . {workdir}/
            RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; fi
            {user_line}
            EXPOSE {" ".join(str(p) for p in ports) if ports else "8080"}
            CMD ["python", "{entry}"]
            ''')

        compose = textwrap.dedent(f'''\
            # Generated by CycleKernel ContainerAgent
            services:
              {name}:
                build: .
                image: {name}:ck
                container_name: {name}
                restart: "no"
                network_mode: "{network}"
                read_only: {"true" if survival else "false"}
                tmpfs:
                  - /tmp
                environment:
            ''')
        env_lines = [f'      - {k}={v}' for k, v in env.items()] or ["      - CK_SANDBOX=1"]
        compose += "\n".join(env_lines) + "\n"
        if ports and network != "none":
            compose += "    ports:\n"
            for p in ports:
                compose += f'      - "{p}:{p}"\n'

        out_dir = Path(artifact_root) if artifact_root else (ARTIFACT_ROOT / "containers" / name)
        out_dir.mkdir(parents=True, exist_ok=True)
        df_path = out_dir / "Dockerfile"
        dc_path = out_dir / "docker-compose.sandbox.yml"
        df_path.write_text(dockerfile, encoding="utf-8")
        dc_path.write_text(compose, encoding="utf-8")

        build_cmd = f"docker build -t {name}:ck {out_dir}"
        run_cmd = f"docker run --rm --network={network} {name}:ck"

        output = {
            "name": name,
            "dockerfile_path": str(df_path),
            "compose_path": str(dc_path),
            "dockerfile": dockerfile,
            "compose": compose,
            "build_command": build_cmd,
            "run_command": run_cmd,
            "network": network,
            "hardened": survival,
            "ports": ports,
            "notes": [
                "Specs only — daemon execution is optional via terminal_execute / server agent",
                "network=none under survival mood",
            ],
        }
        logger.info("Container specs written name=%s dir=%s", name, out_dir)
        return self._wrap(True, output, mood, started)
